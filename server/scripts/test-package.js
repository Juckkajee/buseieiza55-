import assert from 'node:assert/strict'
import {randomBytes} from 'node:crypto'
import {readFile} from 'node:fs/promises'
import {connect,close,read,query} from '../src/db.js'
import {tables,restoreData} from './database-package.js'

// Creates a disposable, uniquely prefixed copy. Never renames or deletes BUS_ objects.
const prefix='F1Q'+randomBytes(3).toString('hex').toUpperCase()+'_'
const names=tables.map(t=>t.replace(/^BUS_/,prefix))
await connect()
try {
  await read(async db=>{
    for(const name of names) assert.equal((await query(db,'SELECT COUNT(*) n FROM user_tables WHERE table_name=:name',{name}))[0].n,0)
    try {
      for(const name of ['schema-oracle-DRAFT.sql','002-web-features-REVIEW.sql','004-booking-cancellation-REVIEW.sql']) {
        const source=await readFile(new URL('../../database-review/'+name,import.meta.url),'utf8')
        for(const sql of source.replace(/^\s*--.*$/gm,'').replaceAll('BUS_',prefix).split(';').map(s=>s.trim()).filter(Boolean)) await db.execute(sql)
      }
      const remap=sql=>sql.replaceAll('BUS_',prefix)
      const proxy={
        execute:(sql,binds={})=>db.execute(remap(sql),Object.fromEntries(Object.entries(binds).map(([k,v])=>[k,k==='name' && tables.includes(v)?v.replace(/^BUS_/,prefix):v]))),
        executeMany:(sql,rows,options)=>db.executeMany(remap(sql),rows,options),
      }
      const snapshot=await restoreData(proxy,new URL('../private/final1-database.json',import.meta.url))
      for(const table of snapshot.tables) assert.equal((await query(proxy,`SELECT COUNT(*) n FROM ${table.name}`))[0].n,table.rows.length)
      await db.rollback()
      console.log('PASS: fresh schema created; snapshot restored with all foreign keys and exact counts for '+tables.length+' tables; import rolled back.')
    } finally {
      await db.rollback()
      for(const name of [...names].reverse()) {
        // Only names generated by this invocation can reach DROP.
        assert.ok(name.startsWith(prefix) && names.includes(name))
        if((await query(db,'SELECT COUNT(*) n FROM user_tables WHERE table_name=:name',{name}))[0].n) await db.execute(`DROP TABLE ${name} CASCADE CONSTRAINTS PURGE`)
      }
      console.log('Disposable schema copy removed; original BUS_ tables untouched.')
    }
  })
} finally {await close()}
