CREATE TABLE BUS_DEPARTMENTS (
    department_id   VARCHAR2(40 CHAR) NOT NULL,
    department_name NVARCHAR2(200) NOT NULL,
    CONSTRAINT BUS_PK_DEPARTMENTS PRIMARY KEY (department_id)
);

CREATE TABLE BUS_POSITIONS (
    position_id   VARCHAR2(40 CHAR) NOT NULL,
    position_name NVARCHAR2(100) NOT NULL,
    CONSTRAINT BUS_PK_POSITIONS PRIMARY KEY (position_id)
);

CREATE TABLE BUS_SCREENS (
    screen_id   VARCHAR2(40 CHAR) NOT NULL,
    screen_name NVARCHAR2(150) NOT NULL,
    CONSTRAINT BUS_PK_SCREENS PRIMARY KEY (screen_id)
);

CREATE TABLE BUS_EMPLOYEES (
    employee_id   VARCHAR2(40 CHAR) NOT NULL,
    full_name     NVARCHAR2(200) NOT NULL,
    username      VARCHAR2(100 CHAR) NOT NULL,
    password_hash VARCHAR2(255 CHAR) NOT NULL,
    phone         VARCHAR2(30 CHAR),
    email         VARCHAR2(254 CHAR),
    department_id VARCHAR2(40 CHAR) NOT NULL,
    position_id   VARCHAR2(40 CHAR) NOT NULL,
    CONSTRAINT BUS_PK_EMPLOYEES PRIMARY KEY (employee_id),
    CONSTRAINT BUS_UQ_EMPLOYEES_USERNAME UNIQUE (username),
    CONSTRAINT BUS_FK_EMP_DEPARTMENT FOREIGN KEY (department_id)
        REFERENCES BUS_DEPARTMENTS (department_id),
    CONSTRAINT BUS_FK_EMP_POSITION FOREIGN KEY (position_id)
        REFERENCES BUS_POSITIONS (position_id)
);

CREATE TABLE BUS_POSITION_PERMISSIONS (
    permission_id VARCHAR2(40 CHAR) NOT NULL,
    position_id   VARCHAR2(40 CHAR) NOT NULL,
    screen_id     VARCHAR2(40 CHAR) NOT NULL,
    can_view      NUMBER(1) DEFAULT 0 NOT NULL,
    can_modify    NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT BUS_PK_POSITION_PERMISSIONS PRIMARY KEY (permission_id),
    CONSTRAINT BUS_UQ_PERMISSION_POS_SCREEN UNIQUE (position_id, screen_id),
    CONSTRAINT BUS_CK_PERMISSION_VIEW CHECK (can_view IN (0, 1)),
    CONSTRAINT BUS_CK_PERMISSION_MODIFY CHECK (can_modify IN (0, 1)),
    CONSTRAINT BUS_FK_PERMISSION_POSITION FOREIGN KEY (position_id)
        REFERENCES BUS_POSITIONS (position_id),
    CONSTRAINT BUS_FK_PERMISSION_SCREEN FOREIGN KEY (screen_id)
        REFERENCES BUS_SCREENS (screen_id)
);

CREATE TABLE BUS_STOPS (
    stop_id   VARCHAR2(40 CHAR) NOT NULL,
    stop_name NVARCHAR2(200) NOT NULL,
    CONSTRAINT BUS_PK_STOPS PRIMARY KEY (stop_id)
);

CREATE TABLE BUS_ROUTES (
    route_id       VARCHAR2(40 CHAR) NOT NULL,
    route_name     NVARCHAR2(150) NOT NULL,
    total_minutes  NUMBER(6) NOT NULL,
    CONSTRAINT BUS_PK_ROUTES PRIMARY KEY (route_id),
    CONSTRAINT BUS_CK_ROUTES_MINUTES CHECK (total_minutes >= 0)
);

CREATE TABLE BUS_ROUTE_STOPS (
    route_stop_id     VARCHAR2(40 CHAR) NOT NULL,
    route_id          VARCHAR2(40 CHAR) NOT NULL,
    stop_id           VARCHAR2(40 CHAR) NOT NULL,
    stop_sequence     NUMBER(6) NOT NULL,
    minutes_from_prev NUMBER(6) NOT NULL,
    CONSTRAINT BUS_PK_ROUTE_STOPS PRIMARY KEY (route_stop_id),
    CONSTRAINT BUS_UQ_ROUTE_STOP_SEQUENCE UNIQUE (route_id, stop_sequence),
    CONSTRAINT BUS_CK_ROUTE_STOP_SEQUENCE CHECK (stop_sequence >= 1),
    CONSTRAINT BUS_CK_ROUTE_STOP_MINUTES CHECK (minutes_from_prev >= 0),
    CONSTRAINT BUS_FK_ROUTE_STOP_ROUTE FOREIGN KEY (route_id)
        REFERENCES BUS_ROUTES (route_id),
    CONSTRAINT BUS_FK_ROUTE_STOP_STOP FOREIGN KEY (stop_id)
        REFERENCES BUS_STOPS (stop_id)
);
-- The same stop_id MAY occur more than once on the same route.
-- Example: Lotus outbound and Lotus inbound use different route_stop_id values.

CREATE TABLE BUS_VEHICLES (
    vehicle_id   VARCHAR2(40 CHAR) NOT NULL,
    license_plate NVARCHAR2(30) NOT NULL,
    vehicle_type NVARCHAR2(50) NOT NULL,
    seat_count   NUMBER(4) NOT NULL,
    CONSTRAINT BUS_PK_VEHICLES PRIMARY KEY (vehicle_id),
    CONSTRAINT BUS_UQ_VEHICLE_PLATE UNIQUE (license_plate),
    CONSTRAINT BUS_CK_VEHICLE_SEATS CHECK (seat_count > 0)
);

CREATE TABLE BUS_TRIP_ROUNDS (
    trip_id            VARCHAR2(40 CHAR) NOT NULL,
    route_id           VARCHAR2(40 CHAR) NOT NULL,
    driver_employee_id VARCHAR2(40 CHAR) NOT NULL,
    vehicle_id         VARCHAR2(40 CHAR) NOT NULL,
    departure_at       TIMESTAMP(0) NOT NULL,
    status             VARCHAR2(20 CHAR) DEFAULT 'SCHEDULED' NOT NULL,
    CONSTRAINT BUS_PK_TRIP_ROUNDS PRIMARY KEY (trip_id),
    CONSTRAINT BUS_UQ_TRIP_VEHICLE UNIQUE (trip_id, vehicle_id),
    CONSTRAINT BUS_CK_TRIP_STATUS CHECK
        (status IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT BUS_FK_TRIP_ROUTE FOREIGN KEY (route_id)
        REFERENCES BUS_ROUTES (route_id),
    CONSTRAINT BUS_FK_TRIP_DRIVER FOREIGN KEY (driver_employee_id)
        REFERENCES BUS_EMPLOYEES (employee_id),
    CONSTRAINT BUS_FK_TRIP_VEHICLE FOREIGN KEY (vehicle_id)
        REFERENCES BUS_VEHICLES (vehicle_id)
);
-- departure_at stores BOTH the departure date and time shown separately in the ER.
-- Proposed convention: all these timestamps represent Asia/Bangkok local time.

CREATE TABLE BUS_USERS (
    user_id       VARCHAR2(40 CHAR) NOT NULL,
    full_name     NVARCHAR2(200) NOT NULL,
    username      VARCHAR2(100 CHAR) NOT NULL,
    password_hash VARCHAR2(255 CHAR) NOT NULL,
    phone         VARCHAR2(30 CHAR),
    user_type     NVARCHAR2(50) NOT NULL,
    CONSTRAINT BUS_PK_APP_USERS PRIMARY KEY (user_id),
    CONSTRAINT BUS_UQ_APP_USERS_USERNAME UNIQUE (username)
);
-- BUS_USERS is the ER's User entity, renamed to avoid the SQL name USER.

CREATE TABLE BUS_BOOKINGS (
    booking_id VARCHAR2(40 CHAR) NOT NULL,
    trip_id    VARCHAR2(40 CHAR) NOT NULL,
    user_id    VARCHAR2(40 CHAR) NOT NULL,
    booked_at  TIMESTAMP(0) DEFAULT LOCALTIMESTAMP NOT NULL,
    status     VARCHAR2(24 CHAR) DEFAULT 'CONFIRMED' NOT NULL,
    CONSTRAINT BUS_PK_BOOKINGS PRIMARY KEY (booking_id),
    CONSTRAINT BUS_UQ_BOOKING_TRIP UNIQUE (booking_id, trip_id),
    CONSTRAINT BUS_CK_BOOKING_STATUS CHECK
        (status IN ('CONFIRMED', 'PARTIALLY_CANCELLED', 'CHECKED_IN',
                    'COMPLETED', 'CANCELLED', 'NO_SHOW')),
    CONSTRAINT BUS_FK_BOOKING_TRIP FOREIGN KEY (trip_id)
        REFERENCES BUS_TRIP_ROUNDS (trip_id),
    CONSTRAINT BUS_FK_BOOKING_USER FOREIGN KEY (user_id)
        REFERENCES BUS_USERS (user_id)
);

CREATE TABLE BUS_BOOKING_DETAILS (
    booking_id          VARCHAR2(40 CHAR) NOT NULL,
    ticket_no           VARCHAR2(30 CHAR) NOT NULL,
    trip_id             VARCHAR2(40 CHAR) NOT NULL,
    vehicle_id          VARCHAR2(40 CHAR) NOT NULL,
    pickup_route_stop_id VARCHAR2(40 CHAR) NOT NULL,
    dropoff_route_stop_id VARCHAR2(40 CHAR) NOT NULL,
    seat_number         VARCHAR2(10 CHAR) NOT NULL,
    travel_at           TIMESTAMP(0) NOT NULL,
    checked_in_at       TIMESTAMP(0),
    status              VARCHAR2(20 CHAR) DEFAULT 'CONFIRMED' NOT NULL,
    qr_token            VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT BUS_PK_BOOKING_DETAILS PRIMARY KEY (booking_id, ticket_no),
    CONSTRAINT BUS_UQ_TICKET_QR UNIQUE (qr_token),
    CONSTRAINT BUS_CK_TICKET_STATUS CHECK
        (status IN ('CONFIRMED', 'CHECKED_IN', 'COMPLETED', 'CANCELLED', 'NO_SHOW')),
    CONSTRAINT BUS_FK_DETAIL_BOOKING_TRIP FOREIGN KEY (booking_id, trip_id)
        REFERENCES BUS_BOOKINGS (booking_id, trip_id),
    CONSTRAINT BUS_FK_DETAIL_TRIP_VEHICLE FOREIGN KEY (trip_id, vehicle_id)
        REFERENCES BUS_TRIP_ROUNDS (trip_id, vehicle_id),
    CONSTRAINT BUS_FK_DETAIL_VEHICLE FOREIGN KEY (vehicle_id)
        REFERENCES BUS_VEHICLES (vehicle_id),
    CONSTRAINT BUS_FK_DETAIL_PICKUP FOREIGN KEY (pickup_route_stop_id)
        REFERENCES BUS_ROUTE_STOPS (route_stop_id),
    CONSTRAINT BUS_FK_DETAIL_DROPOFF FOREIGN KEY (dropoff_route_stop_id)
        REFERENCES BUS_ROUTE_STOPS (route_stop_id),
    CONSTRAINT BUS_CK_TICKET_DIFFERENT_STOPS CHECK
        (pickup_route_stop_id <> dropoff_route_stop_id)
);
-- PROPOSED interpretation of the Partial Key: ticket_no is unique WITHIN booking_id.
-- The two composite foreign keys also ensure the ticket uses its booking's trip
-- and that trip's assigned vehicle. vehicle_id is thereby linked to BUS_VEHICLES.
-- travel_at means the planned pickup date/time for this ticket; confirm this meaning.

-- Proposed seat policy for review: reserve each seat for the WHOLE trip.
-- Cancelled/no-show tickets remain in history but no longer occupy a seat.
-- This policy does NOT implement selling the same seat for non-overlapping segments.
CREATE UNIQUE INDEX BUS_UQ_TICKET_ACTIVE_SEAT ON BUS_BOOKING_DETAILS (
    CASE WHEN status NOT IN ('CANCELLED', 'NO_SHOW') THEN trip_id END,
    CASE WHEN status NOT IN ('CANCELLED', 'NO_SHOW') THEN seat_number END
);

-- Foreign-key indexes to support joins and parent changes.
CREATE INDEX BUS_IX_EMPLOYEE_DEPARTMENT ON BUS_EMPLOYEES (department_id);
CREATE INDEX BUS_IX_EMPLOYEE_POSITION ON BUS_EMPLOYEES (position_id);
CREATE INDEX BUS_IX_PERMISSION_SCREEN ON BUS_POSITION_PERMISSIONS (screen_id);
CREATE INDEX BUS_IX_ROUTE_STOP_STOP ON BUS_ROUTE_STOPS (stop_id);
CREATE INDEX BUS_IX_TRIP_ROUTE ON BUS_TRIP_ROUNDS (route_id);
CREATE INDEX BUS_IX_TRIP_DRIVER ON BUS_TRIP_ROUNDS (driver_employee_id);
CREATE INDEX BUS_IX_TRIP_VEHICLE ON BUS_TRIP_ROUNDS (vehicle_id);
CREATE INDEX BUS_IX_BOOKING_TRIP ON BUS_BOOKINGS (trip_id);
CREATE INDEX BUS_IX_BOOKING_USER ON BUS_BOOKINGS (user_id);
CREATE INDEX BUS_IX_DETAIL_BOOKING_TRIP ON BUS_BOOKING_DETAILS (booking_id, trip_id);
CREATE INDEX BUS_IX_DETAIL_TRIP_VEHICLE ON BUS_BOOKING_DETAILS (trip_id, vehicle_id);
CREATE INDEX BUS_IX_DETAIL_VEHICLE ON BUS_BOOKING_DETAILS (vehicle_id);
CREATE INDEX BUS_IX_DETAIL_PICKUP ON BUS_BOOKING_DETAILS (pickup_route_stop_id);
CREATE INDEX BUS_IX_DETAIL_DROPOFF ON BUS_BOOKING_DETAILS (dropoff_route_stop_id);

